DROP TABLE IF EXISTS games_details CASCADE;
DROP TABLE IF EXISTS games CASCADE;
DROP TABLE IF EXISTS players CASCADE;
DROP TABLE IF EXISTS teams CASCADE;


CREATE TABLE teams (
    TEAM_ID INTEGER PRIMARY KEY,
    LEAGUE_ID INTEGER,
    MIN_YEAR INTEGER,
    MAX_YEAR INTEGER,
    ABBREVIATION VARCHAR(10),
    NICKNAME VARCHAR(50),
    YEARFOUNDED INTEGER,
    CITY VARCHAR(50),
    ARENA VARCHAR(100),
    ARENACAPACITY INTEGER,
    OWNER VARCHAR(100),
    GENERALMANAGER VARCHAR(100),
    HEADCOACH VARCHAR(100),
    DLEAGUEAFFILIATION VARCHAR(100)
);


CREATE TABLE players (
    PLAYER_ID INTEGER PRIMARY KEY,
    PLAYER_NAME VARCHAR(100),
    TEAM_ID INTEGER,
    SEASON INTEGER,
    FOREIGN KEY (TEAM_ID) REFERENCES teams(TEAM_ID)
);


CREATE TABLE games (
    GAME_ID INTEGER PRIMARY KEY,
    GAME_DATE_EST DATE,
    GAME_STATUS_TEXT VARCHAR(50),
    HOME_TEAM_ID INTEGER,
    VISITOR_TEAM_ID INTEGER,
    SEASON INTEGER,
    TEAM_ID_home INTEGER,
    PTS_home INTEGER,
    FG_PCT_home DECIMAL(5,3),
    FT_PCT_home DECIMAL(5,3),
    FG3_PCT_home DECIMAL(5,3),
    AST_home INTEGER,
    REB_home INTEGER,
    TEAM_ID_away INTEGER,
    PTS_away INTEGER,
    FG_PCT_away DECIMAL(5,3),
    FT_PCT_away DECIMAL(5,3),
    FG3_PCT_away DECIMAL(5,3),
    AST_away INTEGER,
    REB_away INTEGER,
    HOME_TEAM_WINS INTEGER,
    FOREIGN KEY (HOME_TEAM_ID) REFERENCES teams(TEAM_ID),
    FOREIGN KEY (VISITOR_TEAM_ID) REFERENCES teams(TEAM_ID)
);


CREATE TABLE games_details (
    GAME_ID INTEGER,
    TEAM_ID INTEGER,
    PLAYER_ID INTEGER,
    TEAM_ABBREVIATION VARCHAR(10),
    TEAM_CITY VARCHAR(50),
    PLAYER_NAME VARCHAR(100),
    NICKNAME VARCHAR(50),
    START_POSITION VARCHAR(10),
    COMMENT VARCHAR(200),
    MIN VARCHAR(10),
    FGM INTEGER,
    FGA INTEGER,
    FG_PCT DECIMAL(5,3),
    FG3M INTEGER,
    FG3A INTEGER,
    FG3_PCT DECIMAL(5,3),
    FTM INTEGER,
    FTA INTEGER,
    FT_PCT DECIMAL(5,3),
    OREB INTEGER,
    DREB INTEGER,
    REB INTEGER,
    AST INTEGER,
    STL INTEGER,
    BLK INTEGER,
    "TO" INTEGER,
    PF INTEGER,
    PTS INTEGER,
    PLUS_MINUS INTEGER,
    PRIMARY KEY (GAME_ID, PLAYER_ID),
    FOREIGN KEY (GAME_ID) REFERENCES games(GAME_ID),
    FOREIGN KEY (PLAYER_ID) REFERENCES players(PLAYER_ID),
    FOREIGN KEY (TEAM_ID) REFERENCES teams(TEAM_ID)
);